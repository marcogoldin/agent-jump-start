test("true round-trip: raw → import → render → re-import is refused", () => {
  const tempDir = makeTempDir();
  try {
    // Step 1: raw skill on disk
    const rawDir = join(tempDir, "raw", "demo-skill");
    writeFile(join(rawDir, "SKILL.md"), RAW_SKILL_MD);

    // Step 2: import into a canonical spec
    const specPath = join(tempDir, "spec.json");
    writeMinimalSpec(specPath);
    const importResult = runCli(["import-skill", "--spec", specPath, "--skill", rawDir]);
    assert.equal(importResult.status, 0, `raw import must succeed.\n${importResult.stderr}`);

    // Step 3: render the spec — this produces a generated SKILL.md mirror
    const renderRoot = join(tempDir, "workspace");
    mkdirSync(renderRoot, { recursive: true });
    const renderResult = runCli(["render", "--spec", specPath, "--target", renderRoot]);
    assert.equal(renderResult.status, 0, `render must succeed.\n${renderResult.stderr}`);

    const generatedSkillDir = join(renderRoot, ".claude", "skills", "demo-skill");
    const generatedSkillMd = join(generatedSkillDir, "SKILL.md");
    assert.ok(existsSync(generatedSkillMd), "render must produce the .claude/skills mirror");

    // Sanity: the rendered SKILL.md really is detectable as generated —
    // otherwise the rest of this test would be meaningless.
    const generatedContent = readFileSync(generatedSkillMd, "utf8");
    assert.match(
      generatedContent,
      /generated_by:\s*Agent Jump Start v|Generated by Agent Jump Start v/,
      "render must embed an Agent Jump Start provenance marker in the mirror",
    );

    // Step 4: try to re-import the rendered mirror into a fresh spec.
    const freshSpecPath = join(tempDir, "fresh-spec.json");
    writeMinimalSpec(freshSpecPath);
    const freshBefore = readFileSync(freshSpecPath, "utf8");

    const reimportResult = runCli([
      "import-skill",
      "--spec", freshSpecPath,
      "--skill", generatedSkillDir,
    ]);
    assert.notEqual(reimportResult.status, 0, "re-importing the rendered mirror must be refused");
    assert.match(reimportResult.stderr, /Refusing to import/);
    assert.match(reimportResult.stderr, /Agent Jump Start/);
    assert.equal(
      readFileSync(freshSpecPath, "utf8"),
      freshBefore,
      "fresh spec must remain untouched when re-import is refused",
    );
  } finally {
    cleanup(tempDir);
  }
});

test("inspectSkillSource surfaces the generated-artifact status with provenance details", async () => {
  const tempDir = makeTempDir();
  try {
    const { inspectSkillSource } = await import("../lib/intake.mjs");

    const fromFm = join(tempDir, "from-fm");
    writeFile(join(fromFm, "SKILL.md"), GENERATED_SKILL_MD_FROM_FRONTMATTER);
    const inspectedFm = inspectSkillSource(fromFm);
    assert.equal(inspectedFm.status, "generated-artifact");
    assert.equal(inspectedFm.provenance.source, "frontmatter");
    assert.equal(inspectedFm.provenance.version, "2.1.0");
    assert.equal(inspectedFm.provenance.generatedFrom, "docs/agent-jump-start/canonical-spec.yaml");

    const fromBody = join(tempDir, "from-body");
    writeFile(join(fromBody, "SKILL.md"), GENERATED_SKILL_MD_FROM_BODY);
    const inspectedBody = inspectSkillSource(fromBody);
    assert.equal(inspectedBody.status, "generated-artifact");
    assert.equal(inspectedBody.provenance.source, "body");
    assert.equal(inspectedBody.provenance.version, "2.0.0");

    const standalone = join(tempDir, "standalone.md");
    writeFile(standalone, GENERATED_SKILL_MD_FROM_FRONTMATTER);
    const inspectedStandalone = inspectSkillSource(standalone);
    assert.equal(inspectedStandalone.status, "generated-artifact");
    assert.equal(inspectedStandalone.provenance.version, "2.1.0");
  } finally {
    cleanup(tempDir);
  }
});
