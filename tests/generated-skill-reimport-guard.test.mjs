test("import-skill refuses a generated directory and leaves the spec untouched", () => {
  const tempDir = makeTempDir();
  try {
    const skillDir = join(tempDir, "demo-skill");
    writeFile(join(skillDir, "SKILL.md"), GENERATED_SKILL_MD_FROM_FRONTMATTER);

    const specPath = join(tempDir, "spec.json");
    writeMinimalSpec(specPath);
    const specBefore = readFileSync(specPath, "utf8");

    const result = runCli(["import-skill", "--spec", specPath, "--skill", skillDir]);
    assert.notEqual(result.status, 0, "import-skill must reject a generated artifact");
    assert.match(result.stderr, /Refusing to import/);
    assert.match(result.stderr, /Agent Jump Start v2\.1\.0/);
    assert.match(result.stderr, /corrupt the spec with synthetic `rcbp-\*` \/ `qr-\*` \/ `dg-\*` ids/);

    const specAfter = readFileSync(specPath, "utf8");
    assert.equal(specAfter, specBefore, "spec must not be modified when import is refused");
  } finally {
    cleanup(tempDir);
  }
});

