test("intake --import classifies a generated SKILL.md as invalid and refuses to import it", () => {
  const tempDir = makeTempDir();
  try {
    const skillDir = join(tempDir, ".claude", "skills", "demo-skill");
    writeFile(join(skillDir, "SKILL.md"), GENERATED_SKILL_MD_FROM_FRONTMATTER);

    const specPath = join(tempDir, "spec.json");
    writeMinimalSpec(specPath);
    const specBefore = readFileSync(specPath, "utf8");

    const result = runCli(["intake", "--spec", specPath, "--target", tempDir, "--import"]);
    // discoverUnmanagedSkills reports the artifact as invalid — the overall
    // exit code reflects invalid discoveries without --import, but with
    // --import the handler prints a report and exits cleanly because no
    // eligible skill was imported. Either way the spec must not be mutated.
    assert.match(result.stdout + result.stderr, /demo-skill/);
    assert.match(
      result.stdout + result.stderr,
      /Agent Jump Start|generated artifact|Re-importing generated/i,
      "intake must surface the generated-artifact diagnostic to the operator",
    );

    assert.equal(
      readFileSync(specPath, "utf8"),
      specBefore,
      "intake --import must not mutate the spec when the only discovery is a generated artifact",
    );
  } finally {
    cleanup(tempDir);
  }
});

