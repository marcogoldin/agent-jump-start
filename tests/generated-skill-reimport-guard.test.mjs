// P0-0 regression: re-importing an Agent Jump Start generated SKILL.md must
// be rejected consistently across validate-skill, import-skill, add-skill,
// and intake --import. A generated artifact that round-trips through the
// import pipeline corrupts the canonical spec with synthetic
// `Rule Categories by Priority` / `Quick Reference` / `Detailed Guidance`
// buckets and recursive `rcbp-*` / `qr-*` / `dg-*` rule ids.
//
// The scenarios covered here are the exact flows called out in the
// P0-0 roadmap section:
//
//   raw skill        → import       → render            (baseline, must still work)
//   rendered skill   → re-import                        (must be rejected)
//   legacy rendered  → re-import                        (must be rejected)
//   rendered with references/scripts/assets → re-import (must be rejected)

import assert from "node:assert/strict";
import test from "node:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const scriptPath = resolve("scripts/agent-jump-start.mjs");

function makeTempDir() {
  return mkdtempSync(join(tmpdir(), "agent-jump-start-p0-0-"));
}

function cleanup(path) {
  rmSync(path, { recursive: true, force: true });
}

function runCli(args, options = {}) {
  return spawnSync(process.execPath, [scriptPath, ...args], { encoding: "utf8", ...options });
}

function writeFile(filePath, content) {
  mkdirSync(resolve(filePath, ".."), { recursive: true });
  writeFileSync(filePath, content, "utf8");
}

function writeMinimalSpec(specPath) {
  writeFile(specPath, JSON.stringify({
    schemaVersion: 1,
    project: { name: "demo", summary: "demo" },
    workspaceInstructions: {
      packageManagerRule: "use existing",
      runtimeRule: "keep runtimes aligned",
      sections: [{ title: "General", rules: ["Keep changes small."] }],
    },
    skills: [],
  }));
}

const RAW_SKILL_MD = `---
name: demo-skill
description: A raw skill fixture that round-trips through the import pipeline.
---

# Demo Skill

## Best Practices

- Keep tests deterministic and independent of network access.
`;

// A SKILL.md that carries the Agent Jump Start provenance marker in the
// frontmatter metadata block. This is the shape produced by the renderer
// for every managed skill.
const GENERATED_SKILL_MD_FROM_FRONTMATTER = `---
name: demo-skill
description: A skill whose frontmatter declares Agent Jump Start provenance.
license: MPL-2.0
metadata:
  title: Demo Skill
  version: 1.0.0
  author: Imported
  generated_by: Agent Jump Start v2.1.0
  generated_from: docs/agent-jump-start/canonical-spec.yaml
---

# Demo Skill

**Version 1.0.0**
Imported

## Best Practices

- Keep tests deterministic.
`;

// A SKILL.md whose frontmatter was operator-scrubbed but whose body still
// carries the blockquote notice emitted by renderers.mjs. The guard must
// trip on the body marker as well, otherwise a simple metadata edit would
// bypass the protection.
const GENERATED_SKILL_MD_FROM_BODY = `---
name: demo-skill
description: A skill with a scrubbed metadata block but a generated body notice.
---

# Demo Skill

> Generated by Agent Jump Start v2.0.0 from \`docs/agent-jump-start/canonical-spec.yaml\`.
> Update the canonical spec and rerun \`render\` instead of hand-editing this file.

## Best Practices

- Keep tests deterministic.
`;

// Legacy artifact: an earlier Agent Jump Start major version. The detector
// is version-agnostic so the guard must still fire.
const LEGACY_GENERATED_SKILL_MD = `---
name: legacy-skill
description: A SKILL.md rendered by an earlier Agent Jump Start major.
license: MPL-2.0
metadata:
  title: Legacy Skill
  version: 0.9.0
  author: Imported
  generated_by: Agent Jump Start v1.2.3
  generated_from: docs/agent-jump-start/canonical-spec.yaml
---

# Legacy Skill

## Best Practices

- Keep tests deterministic.
`;

test("baseline: raw skill -> import-skill -> render stays structurally sane", () => {
  const tempDir = makeTempDir();
  try {
    const skillDir = join(tempDir, "demo-skill");
    writeFile(join(skillDir, "SKILL.md"), RAW_SKILL_MD);

    const specPath = join(tempDir, "spec.json");
    writeMinimalSpec(specPath);

    const importResult = runCli(["import-skill", "--spec", specPath, "--skill", skillDir]);
    assert.equal(
      importResult.status,
      0,
      `import-skill must accept a raw SKILL.md.\nSTDOUT:\n${importResult.stdout}\nSTDERR:\n${importResult.stderr}`,
    );

    const spec = JSON.parse(readFileSync(specPath, "utf8"));
    assert.equal(spec.skills.length, 1);
    assert.equal(spec.skills[0].slug, "demo-skill");
    // The import must not synthesize the collapse-pattern categories that
    // appear only when a generated SKILL.md is fed back into the importer.
    const categoryNames = spec.skills[0].categories.map((c) => c.name);
    assert.ok(
      !categoryNames.includes("Rule Categories by Priority"),
      `Raw import leaked a synthetic category. Got: ${categoryNames.join(", ")}`,
    );
    assert.ok(
      !spec.skills[0].rules.some((r) => /^rcbp-|^qr-|^dg-/.test(r.id)),
      "Raw import produced recursive rule ids; the corruption pattern must only appear on re-import.",
    );

    const renderResult = runCli(["render", "--spec", specPath, "--target", tempDir]);
    assert.equal(
      renderResult.status,
      0,
      `render must succeed on a raw import.\nSTDOUT:\n${renderResult.stdout}\nSTDERR:\n${renderResult.stderr}`,
    );
    assert.ok(existsSync(join(tempDir, ".claude", "skills", "demo-skill", "SKILL.md")));
  } finally {
    cleanup(tempDir);
  }
});

test("validate-skill rejects a generated SKILL.md detected via frontmatter metadata", () => {
  const tempDir = makeTempDir();
  try {
    const skillDir = join(tempDir, "demo-skill");
    writeFile(join(skillDir, "SKILL.md"), GENERATED_SKILL_MD_FROM_FRONTMATTER);

    const result = runCli(["validate-skill", skillDir]);
    assert.notEqual(result.status, 0, "validate-skill must reject a generated artifact");
    assert.match(result.stderr, /Agent Jump Start generated artifact/);
    assert.match(result.stderr, /v2\.1\.0/);
    assert.match(result.stderr, /canonical-spec\.yaml/);
    assert.match(result.stderr, /Import the raw upstream skill instead/);
  } finally {
    cleanup(tempDir);
  }
});

